export function iconMarkup(name, size = 18, extraClass = "") {
  const body = P[name] || P.info;
  return `<svg xmlns="http://www.w3.org/2000/svg" class="icon ${extraClass}" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">${body}</svg>`;
}

export function icon(name, size = 18, extraClass = "") {
  return svgNode(iconMarkup(name, size, extraClass));
}

/** Replace every <i data-icon="name"> placeholder inside `root`. */
export function hydrateIcons(root = document) {
  for (const el of root.querySelectorAll("i[data-icon]")) {
    const node = icon(el.dataset.icon, Number(el.dataset.size) || 18, el.className);
    el.replaceWith(node);
  }
}
